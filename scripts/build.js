'use strict';

/**
 * Builds the self-contained `index.html` at the project root from the modular
 * source in `src/`: the stylesheet and every script are inlined, so the page
 * works anywhere a single file can be opened, uploaded or previewed.
 *
 * Run with `npm run build`. The root `index.html` is generated; edit `src/`.
 */
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');
const SOURCE_DIR = path.join(ROOT, 'src');
const OUTPUT_FILE = path.join(ROOT, 'index.html');

const STYLESHEET_TAG = /<link rel="stylesheet" href="([^"]+)" ?\/?>/;
const SCRIPT_TAG = /<script src="([^"]+)"><\/script>/g;
const BANNER =
  '<!-- GENERATED by `npm run build` from src/. Edit the files in src/, not this one. -->';

const readSource = (relativePath) => fs.readFileSync(path.join(SOURCE_DIR, relativePath), 'utf8');

/** A closing script tag inside inlined code would end the element early. */
const escapeForScript = (code) => code.replaceAll('</script', '<\\/script');

/** @returns {string} the full text of the single-file page */
function buildBundle() {
  const page = readSource('index.html')
    .replace(STYLESHEET_TAG, (_tag, href) => `<style>\n${readSource(href)}</style>`)
    .replace(SCRIPT_TAG, (_tag, src) => `<script>\n${escapeForScript(readSource(src))}</script>`);
  return page.replace('<!doctype html>', `<!doctype html>\n${BANNER}`);
}

if (require.main === module) {
  fs.writeFileSync(OUTPUT_FILE, buildBundle());
  console.log(`Wrote ${path.relative(ROOT, OUTPUT_FILE)}`);
}

module.exports = { buildBundle, OUTPUT_FILE };
