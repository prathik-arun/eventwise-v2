/**
 * Builds the self-contained `index.html` at the project root from the modular
 * source in `src/`: esbuild bundles the ES modules into one script, and that
 * script and the stylesheet are inlined, so the page works anywhere a single
 * file can be opened, uploaded or previewed.
 *
 * Run with `npm run build`. The root `index.html` is generated; edit `src/`.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildSync } from 'esbuild';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE_DIR = path.join(ROOT, 'src');

export const OUTPUT_FILE = path.join(ROOT, 'index.html');

const STYLESHEET_TAG = /<link rel="stylesheet" href="([^"]+)" ?\/?>/;
const MODULE_TAG = /<script type="module" src="([^"]+)"><\/script>/;
const BANNER =
  '<!-- GENERATED by `npm run build` from src/. Edit the files in src/, not this one. -->';

const readSource = (relativePath) => readFileSync(path.join(SOURCE_DIR, relativePath), 'utf8');

/** Bundles an entry module and everything it imports into one classic script. */
function bundleScript(entryPath) {
  const { outputFiles } = buildSync({
    entryPoints: [path.join(SOURCE_DIR, entryPath)],
    bundle: true,
    format: 'iife',
    target: 'es2022',
    write: false,
    logLevel: 'silent',
  });
  // A closing script tag inside inlined code would end the element early.
  return outputFiles[0].text.replaceAll('</script', '<\\/script');
}

/** @returns {string} the full text of the single-file page */
export function buildBundle() {
  const page = readSource('index.html')
    .replace(STYLESHEET_TAG, (_tag, href) => `<style>\n${readSource(href)}</style>`)
    .replace(MODULE_TAG, (_tag, src) => `<script>\n${bundleScript(src)}</script>`);
  return page.replace('<!doctype html>', `<!doctype html>\n${BANNER}`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(OUTPUT_FILE, buildBundle());
  console.log(`Wrote ${path.relative(ROOT, OUTPUT_FILE)}`);
}
